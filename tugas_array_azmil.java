public class tugas_array_azmil {
    public static void main(String[] args) throws Exception {
        int nilai[][] = {
            {80, 75, 90, 65, 85}
        };
        for (int i = 0; i < nilai.length; i++){
            System.out.print("\n"+nilai[i][2]+" ");
        }
    }
}
/*sebab nilai kedua dari array nilai adalah 90, 
maka yang akan di tampilkan adalah 90 ,karena ngambil 
dari nilai 0 terlebih dahulu*/

